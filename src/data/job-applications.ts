export function buildDemoJobApplications(now = Date.now()): JobApplication[] {
  const at = (offsetHours: number) => new Date(now + offsetHours * HOUR).toISOString();

  return DEMO_ROWS.map(({ receivedHoursAgo, notes = [], ...row }) => ({
    ...row,
    receivedAt: at(-receivedHoursAgo),
    notes: notes.map((note, index) => ({
      id: `${row.id}-note-${index}`,
      author: note.author,
      body: note.body,
      createdAt: at(-note.hoursAgo),
    })),
  }));
}
